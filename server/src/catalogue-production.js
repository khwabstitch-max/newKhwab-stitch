export function productionOptionFields(option) {
  const fields = {};
  if ((option.serviceType || "stitching") === "stitching" && option.garments?.includes("alteration")) fields.garments = option.garments.filter(garment => garment !== "alteration");
  if (option.kind === "sleeve" && SLEEVE_COMPATIBILITY[option.name]) fields.compatibleLengthStyles = [...SLEEVE_COMPATIBILITY[option.name]];
  if (!option.description?.trim()) fields.description = "A stitching preference for compatible garments. Suitability for your fabric and the final charge are confirmed before work begins.";
  if (!option.descriptionHi?.trim()) fields.descriptionHi = "उपयुक्त कपड़ों के लिए सिलाई का विकल्प। आपके कपड़े के अनुसार इसकी उपयुक्तता और अंतिम शुल्क काम शुरू होने से पहले तय होगा।";
  return fields;
}
