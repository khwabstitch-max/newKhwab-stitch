export function productionDesignProfile(design) {
  return PRODUCTION_DESIGN_PROFILES.find(profile => profile.slug === design?.slug && profile.garment === design?.garment && (String(design?._id) === profile.id || design?.code === profile.legacyCode)) || null;
}
export function productionDesignContent(design) {
  const profile = productionDesignProfile(design);
  return profile ? structuredClone(profile.content) : null;
}
export function publicProductionDesign(design) {
  const profile = productionDesignProfile(design);
  return profile && /^demo(?:\s|[·:.-])/i.test(design.title || "")
    ? { ...design, ...structuredClone(profile.content) }
    : design;
}
