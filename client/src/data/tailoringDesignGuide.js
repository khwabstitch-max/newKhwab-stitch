export function findNeckGuide(query) {
  if (!query) return null;
  const q = String(query).toLowerCase().trim();

  // Sleeves or back designs must never match front neck designs
  if (/\b(sleeve|sleeves|baaju|baju|armhole|back)\b/i.test(q)) {
    return null;
  }

  // 1. Exact id or name match
  for (const c of neckDesignCards) {
    if (q === c.id || q === c.key) return c;
    if (q === c.name.toLowerCase() || (c.nameHi && q === c.nameHi)) return c;
  }

  // 2. Specific keyword matches
  if (/\bround\b|gol|गोल/i.test(q)) return neckDesignCards.find((c) => c.id === "round-neck");
  if (/\bv\s*[-_]?\s*(neck|gala|cut|shape)?\b|वी\s*गला|वी\s*आकार/i.test(q)) {
    return neckDesignCards.find((c) => c.id === "v-neck");
  }
  if (/\bboat\b|naav|नाव/i.test(q)) return neckDesignCards.find((c) => c.id === "boat-neck");
  if (/\bcollar\b|कॉलर/i.test(q)) {
    if (/mandarin|chinese|चाइनीज/i.test(q)) return neckDesignCards.find((c) => c.id === "mandarin-collar");
    return neckDesignCards.find((c) => c.id === "collar-neck");
  }
  if (/\bsquare\b|chokor|chaukor|चौकोर|चोकोर/i.test(q)) return neckDesignCards.find((c) => c.id === "square-neck");
  if (/\bsweetheart\b|dil\b|दिल/i.test(q)) return neckDesignCards.find((c) => c.id === "sweetheart-neck");
  if (/\bhigh\s*[-_]?\s*neck\b|band\s*gala|बंद\s*गला/i.test(q)) return neckDesignCards.find((c) => c.id === "high-neck");
  if (/\bmandarin\b|chinese|चाइनीज/i.test(q)) return neckDesignCards.find((c) => c.id === "mandarin-collar");

  return null;
}

