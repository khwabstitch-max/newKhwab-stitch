  if (/elbow|1\/2|half|aadhi|आधी/i.test(q)) return sleeveLengthCards.find((c) => c.id === "elbow");
  if (/full|poori|पूरी/i.test(q)) return sleeveLengthCards.find((c) => c.id === "full");

  for (const c of sleeveLengthCards) {
    if (q === c.id || q === c.key || q === c.name.toLowerCase()) return c;
  }
  return null;
